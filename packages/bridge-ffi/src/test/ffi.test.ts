/**
 * FFI generator tests: structure, determinism and ABI consistency across
 * the Rust and Go sides (symbol agreement, header agreement, status
 * codes).
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { makePaymentsIR, makeMinimalIR } from '@bridge/generators/dist/test/fixtures.js';
import type { IRPackage } from '@bridge/core';
import {
  FFI_STATUS,
  cHeaderFile,
  echoSymbol,
  ffiCrateName,
  ffiLibName,
  freeSymbol,
  generateFfi,
  methodSymbol,
} from '../index';
import type { GeneratedFile } from '../util';

const ir = makePaymentsIR();

function byPath(files: GeneratedFile[], path: string): GeneratedFile {
  const file = files.find((f) => f.path === path);
  assert.ok(file !== undefined, `expected generated file ${path}`);
  return file;
}

function commonHeader(content: string): void {
  assert.match(content, /Code generated by bridge DO NOT EDIT\./);
  assert.ok(!content.includes('TODO'), 'generated output must not contain TODO');
}

test('rust-ffi: expected file list and structure', () => {
  const files = generateFfi(ir, { target: 'rust-ffi' });
  const paths = files.map((f) => f.path).sort();
  assert.deepEqual(paths, [
    'Cargo.toml',
    'include/bridge_payments_v1.h',
    'src/enums.rs',
    'src/ffi.rs',
    'src/lib.rs',
    'src/types.rs',
    'src/validate.rs',
    'tests/abi.rs',
  ]);
  const cargo = byPath(files, 'Cargo.toml');
  assert.match(cargo.content, /^name = "bridge-payments-v1-ffi"$/m);
  assert.match(cargo.content, /crate-type = \["cdylib", "rlib"\]/);
  const lib = byPath(files, 'src/lib.rs');
  commonHeader(lib.content);
  assert.match(lib.content, /pub struct Handlers \{/);
  assert.match(lib.content, /install_handlers/);
  const ffi = byPath(files, 'src/ffi.rs');
  commonHeader(ffi.content);
  assert.match(ffi.content, /catch_unwind\(AssertUnwindSafe/);
  // One entry point per method with the canonical symbol.
  assert.match(ffi.content, /pub extern "C" fn bridge_payments_v1_payments_create_payment_call\(/);
  assert.match(ffi.content, /pub extern "C" fn bridge_payments_v1_free\(/);
  // Handler presence is checked BEFORE request parsing.
  assert.match(ffi.content, /no_handler/);
  const header = byPath(files, 'include/bridge_payments_v1.h');
  commonHeader(header.content.replace(/^\/\/ /gm, '// '));
  assert.match(header.content, /int32_t bridge_payments_v1_payments_create_payment_call\(/);
  assert.match(header.content, /void bridge_payments_v1_free\(/);
  for (const file of files) {
    if (file.path.endsWith('.h')) continue; // C header style checked above
    if (file.path === 'Cargo.toml') continue; // TOML header is a comment block
    commonHeader(file.content);
  }
});

