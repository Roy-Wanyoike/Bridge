/** Strips string/char literals so brace counting ignores their contents. */
function stripLiterals(content: string): string {
  return content
    .replace(/"(?:[^"\\\n]|\\.)*"/g, '""')
    .replace(/'(?:[^'\\\n]|\\.)*'/g, "''")
    .replace(/\/\/[^\n]*/g, '');
}

