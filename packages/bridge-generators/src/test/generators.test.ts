function byPath(files: GeneratedFile[], path: string): GeneratedFile {
  const file = files.find((f) => f.path === path);
  assert.ok(file !== undefined, `expected generated file ${path}`);
  return file;
}

function commonHeader(content: string): void {
  assert.ok(
    /^(\/\/|#)? ?Code generated by bridge DO NOT EDIT\./m.test(content),
    'missing DO-NOT-EDIT header',
  );
  assert.ok(content.includes(`Generator version: ${GENERATOR_VERSION}`), 'missing generator version');
  assert.ok(content.includes('Package: payments.v1'), 'missing package name');
  assert.ok(!content.includes('TODO'), 'generated output must not contain TODO');
}

