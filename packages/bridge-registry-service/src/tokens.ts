/**
 * Issued-token lifecycle primitives (audit item R1).
 *
 * Static tokens in {@link ./auth.ts} (the `TokenTable`) are a bootstrap
 * mechanism: raw secrets live in configuration, never expire and share one
 * audit identity per tenant. This module implements the durable alternative:
 * tokens CREATED through the API with
 *
 * - a fixed org binding (the creating principal's org),
 * - an optional expiry (`expiresAt`, stored as an ISO-8601 UTC string),
 * - an optional scope (`registry:read` | `registry:publish` | `registry:admin`),
 * - a per-credential audit identity (`id`, surfaced as `Principal.tokenId`).
 *
 * Secrets are returned EXACTLY ONCE at creation. Storage keeps only
 * `sha256(salt + ':' + secret)` where `salt` is a random per-record value
 * generated by this service — the salt is stored next to the digest
 * (`<salt-hex>$<digest-hex>`, the same shape password hashes use), which is
 * standard practice: it is not secret material, and it keeps the token table
 * self-contained so hashes survive restarts with zero configuration.
 *
 * The plaintext format is `bri_<id>_<secret>`: the record id travels inside
 * the token so authentication is a single indexed lookup by id followed by a
 * constant-time digest comparison — the prefix is RESERVED for issued tokens.
 */

import { createHash, randomBytes, randomUUID, timingSafeEqual } from 'node:crypto';
import { SCOPES } from './types';
import type { AccessLevel, IssuedTokenMeta, IssuedTokenRecord, TokenScope } from './types';

/** Reserved plaintext prefix for service-issued tokens. */
export const ISSUED_TOKEN_PREFIX = 'bri_';

/** Entropy of the secret part: 32 random bytes (base64url, ~43 chars). */
export const ISSUED_TOKEN_SECRET_BYTES = 32;

/** Salt size per record: 16 random bytes (128 bits), hex-encoded. */
export const ISSUED_TOKEN_SALT_BYTES = 16;

/** Bounds for the optional client-supplied label. */
export const TOKEN_NAME_MAX_LENGTH = 128;

/**
 * A freshly minted token: the plaintext (shown once) plus the record id it
 * will be stored under.
 */
export interface GeneratedToken {
  /** Full bearer plaintext, `bri_<id>_<secret>`. Return to the caller once. */
  plaintext: string;
  /** Record id (also embedded in the plaintext for direct lookup). */
  id: string;
}

/** Generate a new issued-token plaintext + record id (crypto-random). */
export function generateIssuedToken(): GeneratedToken {
  const id = randomUUID();
  const secret = randomBytes(ISSUED_TOKEN_SECRET_BYTES).toString('base64url');
  return { plaintext: `${ISSUED_TOKEN_PREFIX}${id}_${secret}`, id };
}

/**
 * Compute the stored `token_hash` for a plaintext: `<salt-hex>$<sha256-hex>`
 * over `salt-hex + ':' + plaintext`. `salt` defaults to a fresh random value
 * (creation); verification always passes the salt read from the record.
 */
export function hashIssuedToken(plaintext: string, salt: Buffer = randomBytes(ISSUED_TOKEN_SALT_BYTES)): string {
  return `${salt.toString('hex')}$${digestOf(salt.toString('hex'), plaintext)}`;
}

function digestOf(saltHex: string, plaintext: string): string {
  return createHash('sha256').update(`${saltHex}:${plaintext}`, 'utf8').digest('hex');
}

/** Parse a plaintext into its record id and secret part; null when malformed. */
export function parseIssuedToken(plaintext: string): { id: string; secret: string } | null {
  if (typeof plaintext !== 'string' || !plaintext.startsWith(ISSUED_TOKEN_PREFIX)) return null;
  const rest = plaintext.slice(ISSUED_TOKEN_PREFIX.length);
  const underscore = rest.indexOf('_');
  if (underscore <= 0) return null;
  const id = rest.slice(0, underscore);
  const secret = rest.slice(underscore + 1);
  // A record id is a UUID: 36 chars, hex + hyphens (never an underscore).
  if (!/^[0-9a-fA-F-]{8,64}$/.test(id) || secret.length === 0) return null;
  return { id, secret };
}

/**
 * Constant-time verification of a plaintext against a stored
 * `<salt>$<digest>` hash. Malformed inputs never match.
 */
export function verifyIssuedTokenHash(plaintext: string, storedHash: string): boolean {
  const dollar = storedHash.indexOf('$');
  if (dollar <= 0) return false;
  const saltHex = storedHash.slice(0, dollar);
  const expected = storedHash.slice(dollar + 1);
  if (!/^[0-9a-f]{32}$/.test(saltHex) || !/^[0-9a-f]{64}$/.test(expected)) return false;
  const actual = digestOf(saltHex, plaintext);
  const a = Buffer.from(actual, 'hex');
  const b = Buffer.from(expected, 'hex');
  return a.length === b.length && timingSafeEqual(a, b);
}

/** Shape of a stored hash (used by tests to prove plaintext is never stored). */
export const TOKEN_HASH_PATTERN = /^[0-9a-f]{32}\$[0-9a-f]{64}$/;

/**
 * API-safe projection of a stored record: metadata only — the token hash is
 * dropped so no listing/audit response can ever carry credential material.
 */
export function issuedTokenMeta(record: IssuedTokenRecord): IssuedTokenMeta {
  const meta: IssuedTokenMeta = {
    id: record.id,
    org: record.org,
    scope: record.scope,
    createdBy: record.createdBy,
    createdAt: record.createdAt,
    expiresAt: record.expiresAt,
    revokedAt: record.revokedAt,
  };
  if (record.name !== undefined) meta.name = record.name;
  return meta;
}

/** True when `scope` is one of the scopes the service understands. */
export function isValidTokenScope(scope: unknown): scope is TokenScope {
  return scope === SCOPES.read || scope === SCOPES.publish || scope === SCOPES.admin;
}

/**
 * Map a token scope to its numeric access level (1 read, 2 publish, 3 admin).
 * Invalid scopes map to the lowest level — callers validate first.
 */
export function scopeToAccessLevel(scope: string): AccessLevel {
  if (scope === SCOPES.admin) return 3;
  if (scope === SCOPES.publish) return 2;
  return 1;
}

/** True when an ISO-8601 `expiresAt` value has passed at `nowMs`. */
export function isTokenExpired(expiresAt: string | null, nowMs: number): boolean {
  if (expiresAt === null) return false;
  const t = Date.parse(expiresAt);
  return Number.isFinite(t) && t <= nowMs;
}
